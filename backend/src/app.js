import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import { env } from './config/env.js';
import healthRoutes from './routes/healthRoutes.js';
import caseRoutes from './routes/caseRoutes.js';
import uploadRoutes from './routes/uploadRoutes.js';
import analysisRoutes from './routes/analysisRoutes.js';
import { caseEvidence, evidence } from './routes/evidenceRoutes.js';
import { errorHandler } from './middleware/errorHandler.js';
import { apiRateLimit } from './middleware/rateLimitMiddleware.js';
import claimRoutes from './routes/claimRoutes.js';
import caseClaimRoutes from './routes/caseClaimRoutes.js';
import reviewRoutes from './routes/reviewRoutes.js';
import authRoutes from './routes/authRoutes.js';
import handoverRoutes from './routes/handoverRoutes.js';
const app = express();
app.disable('x-powered-by'); app.use(helmet()); app.use(cors({ origin: env.corsOrigin })); app.use(express.json({ limit: '1mb' }));
app.use('/api', apiRateLimit);
app.use('/api/health', healthRoutes);
app.use('/api/auth', authRoutes);
app.use('/api', handoverRoutes); app.use('/api/cases', caseRoutes);
app.use('/api/cases/:id/claims', caseClaimRoutes);
app.use('/api/cases/:id/reviews', reviewRoutes);
app.use('/api/claims', claimRoutes);
app.use('/api/cases', uploadRoutes);
app.use('/api/cases/:id/evidence', caseEvidence);
app.use('/api/evidence', evidence);
app.use('/api/cases/:id', analysisRoutes);
app.use((req, res) => res.status(404).json({ success: false, message: 'Route not found', error: { code: 'ROUTE_NOT_FOUND' } }));
app.use(errorHandler);
export default app;
